"""Verifies citation traces for insights generated by File Agent, Deep Research, and Data Commons."""

import argparse
import asyncio
import enum
import logging
import os
import sys
import time

from panoramic_insights import insights_prompts
from google import genai
from google.genai import types
import pandas as pd
from pydantic import BaseModel


class VerificationStatus(str, enum.Enum):
  PASS = "PASS"
  FAIL = "FAIL"
  SKIP = "SKIP"


class VerificationResult(BaseModel):
  verified: bool
  reason: str


# Sandbox verification runs are long multi-step code executions. Running many
# in one environment at once slows each one past the timeout (9 concurrent runs
# all exceeded 600s, while one alone took about 5 minutes), so they are capped
# per environment independently of the LLM call concurrency.
DEFAULT_MAX_SANDBOX_CONCURRENCY = 3


logging.basicConfig(
    level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s"
)


async def poll_interaction(client, interaction_id, timeout_sec=600, interval_sec=5):
  """Polls a background sandbox interaction asynchronously until completion."""
  start_time = time.time()
  while time.time() - start_time < timeout_sec:
    interaction = await asyncio.to_thread(client.interactions.get, interaction_id)
    status = interaction.status
    logging.info(f"Interaction {interaction_id} status: {status}")
    if status == "completed":
      return interaction.output_text
    elif status in ["failed", "cancelled"]:
      raise RuntimeError(
          f"Sandbox interaction {interaction_id} failed with status: {status}"
      )
    await asyncio.sleep(interval_sec)
  raise TimeoutError(
      f"Sandbox interaction {interaction_id} timed out after {timeout_sec}"
      " seconds"
  )


async def verify_single_insight(
    client,
    eval_model: str,
    file_agent_env_id: str,
    fact_checking_env_id: str,
    row: pd.Series,
    index: int,
    mapped_work_dir: str = "",
    sandbox_timeout_sec: int = 600,
) -> tuple[VerificationStatus, str]:
  """Runs sandbox code execution and evaluates citation verification for a single insight."""
  insight = row.get("full_insight", "")
  trace = row.get("citation_text", "")
  link = row.get("citation_link", "")
  source = str(row.get("source", "file_agent"))

  logging.info(f"[{index}] Verifying Source '{source}' Insight: {insight}")
  logging.info(f"[{index}] Trace: {trace}")
  logging.info(f"[{index}] Link: {link}")

  sandbox_work_dir = mapped_work_dir if mapped_work_dir else "/workspace"

  # Determine sandbox prompt and environment according to source type
  if source in ("deep_research", "data_commons"):
    env_id = fact_checking_env_id
  else:
    env_id = file_agent_env_id

  sandbox_prompt = insights_prompts.get_verification_sandbox_prompt(
      source=source,
      link=link,
      trace=trace,
      insight=insight,
      sandbox_work_dir=sandbox_work_dir,
  )

  logging.info(
      f"[{index}] Launching verification sandbox task for source '{source}' using env '{env_id}'..."
  )
  try:
    kwargs = {
        "input": sandbox_prompt,
        "agent": "antigravity-preview-05-2026",
        "background": True,
        "tools": [{"type": "code_execution"}],
    }
    if env_id and env_id != "fact_checking_sandbox":
      kwargs["environment"] = env_id
    else:
      kwargs["environment"] = {
          "type": "remote",
      }
    interaction = await asyncio.to_thread(client.interactions.create, **kwargs)

    sandbox_output = await poll_interaction(
        client, interaction.id, timeout_sec=sandbox_timeout_sec
    )
    logging.info(f"[{index}] Sandbox execution complete.")
    logging.info(f"[{index}] Sandbox Output:\n{sandbox_output}\n")
  except Exception as e:
    logging.warning(f"[{index}] Sandbox execution skipped due to error: {e}")
    return VerificationStatus.SKIP, f"Sandbox execution error: {e}"

  # Evaluate if output matches insight
  eval_prompt = f"""You are a verification auditor.
We want to verify if a data insight is correct based on the sandbox execution results of its data trace.

- Source Type: "{source}"
- Raw Data Insight: "{insight}"
- Data Trace: "{trace}"
- Sandbox Verification Output: "{sandbox_output}"

Does the Sandbox Verification Output successfully verify, confirm, or match the numbers/findings claimed in the Raw Data Insight?
"""

  logging.info(f"[{index}] Calling LLM evaluator to match outputs...")
  max_retries = 4
  for attempt in range(max_retries):
    try:
      response = await asyncio.to_thread(
          client.models.generate_content,
          model=eval_model,
          contents=eval_prompt,
          config=types.GenerateContentConfig(
              response_mime_type="application/json",
              response_schema=VerificationResult,
              temperature=0.0,
          ),
      )

      verified = response.parsed.verified
      reason = response.parsed.reason

      if verified:
        logging.info(f"[{index}] ✅ PASS ({source}): {reason}")
        return VerificationStatus.PASS, reason
      else:
        logging.error(f"[{index}] ❌ FAIL ({source}): {reason}")
        return VerificationStatus.FAIL, reason
    except Exception as e:
      err_str = str(e)
      if ("503" in err_str or "429" in err_str or "UNAVAILABLE" in err_str) and attempt < max_retries - 1:
        wait_sec = (attempt + 1) * 3
        logging.warning(f"[{index}] Rate limit/503 on attempt {attempt+1}: {e}. Retrying in {wait_sec}s...")
        await asyncio.sleep(wait_sec)
      else:
        logging.warning(f"[{index}] Evaluation skipped due to error: {e}")
        return VerificationStatus.SKIP, f"Evaluation error: {e}"


async def verify_all_insights(
    client,
    eval_model: str,
    file_agent_env_id: str,
    fact_checking_env_id: str,
    df: pd.DataFrame,
    file_agent_metadata_csv: str | None = None,
    output_csv: str = "",
    sandbox_timeout_sec: int = 600,
    max_sandbox_concurrency: int = DEFAULT_MAX_SANDBOX_CONCURRENCY,
    prior_statuses: list[str] | None = None,
    prior_reasons: list[str] | None = None,
) -> tuple[list[str], list[str]]:
  """Runs verification on all insights in parallel with controlled per-sandbox concurrency and exact 1:1 routing.

  Args:
    client: Default genai client.
    eval_model: Model used to judge sandbox output.
    file_agent_env_id: Comma-separated File Agent sandbox environment IDs.
    fact_checking_env_id: Comma-separated fact checking environment IDs.
    df: Insights to verify.
    file_agent_metadata_csv: Optional Phase 2 File Agent CSV with env IDs.
    output_csv: Optional checkpoint path.
    sandbox_timeout_sec: Seconds to wait for one sandbox run.
    max_sandbox_concurrency: Maximum sandbox runs in flight per environment,
      counted across all sources that share that environment.
    prior_statuses: Statuses from an earlier pass, in row order. Rows that
      already hold PASS or FAIL are kept and only the remaining rows are
      verified.
    prior_reasons: Reasons matching `prior_statuses`.

  Returns:
    Lists of verification statuses and reasons, in row order.
  """
  import collections

  # Build proposal-to-sandbox & proposal-to-workdir mapping
  fa_mapping = {}
  fa_workdir_mapping = {}
  if file_agent_metadata_csv and os.path.exists(file_agent_metadata_csv):
    try:
      meta_df = pd.read_csv(file_agent_metadata_csv)
      for _, mrow in meta_df.iterrows():
        prop_val = mrow.get("proposal")
        key = (mrow.get("topic"), prop_val)
        if "env_id" in meta_df.columns and pd.notna(mrow.get("env_id")):
          fa_mapping[key] = str(mrow.get("env_id"))
        if (
            "sandbox_work_dir" in meta_df.columns
            and pd.notna(mrow.get("sandbox_work_dir"))
            and str(mrow.get("sandbox_work_dir")).strip()
        ):
          fa_workdir_mapping[key] = str(mrow.get("sandbox_work_dir")).strip()
      logging.info(f"Loaded {len(fa_mapping)} env_ids and {len(fa_workdir_mapping)} work_dirs from {file_agent_metadata_csv}.")
    except Exception as e:
      logging.warning(f"Could not load file agent metadata mapping: {e}")

  # One limit per environment ID. File Agent and fact checking runs that land
  # in the same environment share it, since they compete for the same sandbox.
  sandbox_semaphores = collections.defaultdict(
      lambda: asyncio.Semaphore(max_sandbox_concurrency)
  )

  file_agent_pool = [e.strip() for e in file_agent_env_id.split(",") if e.strip()]
  fact_checking_pool = [e.strip() for e in fact_checking_env_id.split(",") if e.strip()]

  status_list = [VerificationStatus.SKIP.value] * len(df)
  reason_list = ["Not processed"] * len(df)

  # Support resume from existing output CSV if present
  if output_csv and os.path.exists(output_csv):
    try:
      existing_df = pd.read_csv(output_csv)
      if "verification_status" in existing_df.columns and len(existing_df) == len(df):
        for i, row in existing_df.iterrows():
          if pd.notna(row.get("verification_status")) and row.get("verification_status") in ("PASS", "FAIL"):
            status_list[i] = row["verification_status"]
            reason_list[i] = str(row.get("verification_reason", ""))
        done_count = sum(1 for s in status_list if s in ("PASS", "FAIL"))
        logging.info(f"Resuming from existing checkpoint: {done_count}/{len(df)} rows already completed.")
    except Exception as e:
      logging.warning(f"Failed to read existing output CSV for resume: {e}")

  # Results of an earlier pass take precedence over the checkpoint file.
  if prior_statuses is not None:
    if len(prior_statuses) != len(df):
      raise ValueError(
          f"prior_statuses has {len(prior_statuses)} entries for {len(df)} rows."
      )
    if prior_reasons is None:
      prior_reasons = [""] * len(df)
    for i, prior_status in enumerate(prior_statuses):
      if prior_status in (VerificationStatus.PASS.value, VerificationStatus.FAIL.value):
        status_list[i] = prior_status
        reason_list[i] = prior_reasons[i]

  save_lock = asyncio.Lock()

  async def _save_checkpoint():
    if output_csv:
      async with save_lock:
        df_copy = df.copy()
        df_copy["verification_status"] = status_list
        df_copy["verification_reason"] = reason_list
        df_copy.to_csv(output_csv, index=False)

  async def _worker(row, idx):
    if status_list[idx - 1] in ("PASS", "FAIL"):
      logging.info(f"[{idx}] Already completed in previous checkpoint ({status_list[idx - 1]}). Skipping.")
      return VerificationStatus(status_list[idx - 1]), reason_list[idx - 1]

    topic = row.get("topic")
    proposal = row.get("proposal")
    source = str(row.get("source", "file_agent"))

    # Determine assigned File Agent sandbox
    mapped_env = fa_mapping.get((topic, proposal))
    mapped_workdir = fa_workdir_mapping.get((topic, proposal), "/workspace")

    if mapped_env:
      assigned_fa_env = mapped_env
    elif file_agent_pool:
      assigned_fa_env = file_agent_pool[idx % len(file_agent_pool)]
    else:
      assigned_fa_env = ""

    assigned_fc_env = fact_checking_pool[idx % len(fact_checking_pool)] if fact_checking_pool else "fact_checking_sandbox"

    # Select the semaphore of the environment this run will actually use,
    # matching the routing in verify_single_insight.
    if source in ("deep_research", "data_commons"):
      target_env = assigned_fc_env
    else:
      target_env = assigned_fa_env
    target_sem = sandbox_semaphores[target_env]

    async with target_sem:
      status, reason = await verify_single_insight(
          client,
          eval_model,
          assigned_fa_env,
          assigned_fc_env,
          row,
          idx,
          mapped_work_dir=mapped_workdir,
          sandbox_timeout_sec=sandbox_timeout_sec,
      )
      status_list[idx - 1] = status.value
      reason_list[idx - 1] = reason
      await _save_checkpoint()
      return status, reason

  tasks = [
      _worker(row, i + 1)
      for i, row in df.reset_index(drop=True).iterrows()
  ]
  results = await asyncio.gather(*tasks)
  final_status_list = [status.value for status, _ in results]
  final_reason_list = [reason for _, reason in results]
  return final_status_list, final_reason_list


def count_statuses(status_list: list[str]) -> dict[str, int]:
  """Counts PASS, FAIL and SKIP entries of a status list.

  Args:
    status_list: Verification statuses as strings.

  Returns:
    Counts keyed on the `VerificationStatus` values.
  """
  counts = {}
  for status in VerificationStatus:
    counts[status.value] = 0
  for status in status_list:
    if status in counts:
      counts[status] += 1
  return counts


async def verify_insights_with_retries(
    max_passes: int = 2, **verify_kwargs
) -> tuple[list[str], list[str]]:
  """Verifies all insights, re-verifying SKIP rows in further passes.

  SKIP results come from sandbox timeouts and other infrastructure errors that
  usually succeed when tried again. Every pass after the first only re-runs the
  rows that are still SKIP; rows already holding PASS or FAIL keep their
  result.

  Args:
    max_passes: Maximum number of verification passes, including the first.
    **verify_kwargs: Keyword arguments for `verify_all_insights`.

  Returns:
    Lists of the final verification statuses and reasons, in row order.

  Raises:
    ValueError: If `max_passes` is smaller than 1.
  """
  if max_passes < 1:
    raise ValueError(f"max_passes must be at least 1, got {max_passes}.")

  status_list = None
  reason_list = None
  for pass_number in range(1, max_passes + 1):
    if pass_number > 1:
      skipped = count_statuses(status_list)[VerificationStatus.SKIP.value]
      if skipped == 0:
        break
      logging.info(
          f"Pass {pass_number}/{max_passes}: re-verifying {skipped} SKIP"
          " row(s)."
      )
    status_list, reason_list = await verify_all_insights(
        prior_statuses=status_list,
        prior_reasons=reason_list,
        **verify_kwargs,
    )
    counts = count_statuses(status_list)
    logging.info(
        f"Pass {pass_number}/{max_passes} done:"
        f" PASS={counts[VerificationStatus.PASS.value]}"
        f" FAIL={counts[VerificationStatus.FAIL.value]}"
        f" SKIP={counts[VerificationStatus.SKIP.value]}"
    )
  return status_list, reason_list


def build_arg_parser() -> argparse.ArgumentParser:
  """Builds the command-line parser.

  Returns:
    The argument parser for this script.
  """
  parser = argparse.ArgumentParser(
      description="Verify citation traces for insights from all sources."
  )
  parser.add_argument(
      "--input_csv",
      required=True,
      help="Path to phase_3_structured_insights.csv",
  )
  parser.add_argument(
      "--output_csv",
      default="",
      help="Optional path to save verified CSV. Defaults to updating input_csv.",
  )
  parser.add_argument(
      "--file_agent_environment_id",
      default=os.environ.get("AGENT_ENVIRONMENT_ID", ""),
      help="File Agent sandbox environment ID(s) (reads from AGENT_ENVIRONMENT_ID env var if not set)",
  )
  parser.add_argument(
      "--file_agent_metadata_csv",
      default=None,
      help="Path to Phase 2 file agent output CSV containing env_id per proposition.",
  )
  parser.add_argument(
      "--fact_checking_agent_environment_id",
      default="fact_checking_sandbox",
      help="Clean fact checking sandbox environment ID for DR and DC",
  )
  parser.add_argument(
      "--gemini_api_key",
      default=os.environ.get("GEMINI_API_KEY", ""),
      help="Gemini API Key",
  )
  parser.add_argument(
      "--model_name",
      default="gemini-3.8-flash",
      help="Model name for evaluation",
  )
  parser.add_argument(
      "--max_sandbox_concurrency",
      type=int,
      default=DEFAULT_MAX_SANDBOX_CONCURRENCY,
      help=(
          "Maximum verification sandbox runs in flight per environment,"
          f" across all sources. Default: {DEFAULT_MAX_SANDBOX_CONCURRENCY}."
      ),
  )
  parser.add_argument(
      "--sandbox_timeout_sec",
      type=int,
      default=600,
      help=(
          "Seconds to wait for a verification sandbox to finish before giving"
          " up and recording SKIP. Raise this when many insights share one"
          " sandbox environment, since contention makes individual runs much"
          " slower. Default: 600."
      ),
  )
  parser.add_argument(
      "--max_passes",
      type=int,
      default=2,
      help=(
          "Total number of verification passes. After each pass, rows whose"
          " status is SKIP (sandbox timeouts, infrastructure errors) are"
          " re-verified in a further pass until none are left or the limit is"
          " reached. Default: 2."
      ),
  )
  return parser


async def main():
  args = build_arg_parser().parse_args()

  if not args.gemini_api_key:
    logging.error("Gemini API key is required.")
    sys.exit(1)

  client = genai.Client(api_key=args.gemini_api_key)

  if not os.path.exists(args.input_csv):
    logging.error(f"Input CSV {args.input_csv} does not exist.")
    sys.exit(1)

  df = pd.read_csv(args.input_csv)
  logging.info(f"Found {len(df)} total insights to verify across all sources.")
  if df.empty:
    logging.info("Nothing to verify. Exiting.")
    sys.exit(0)

  out_path = args.output_csv if args.output_csv else args.input_csv

  status_list, reason_list = await verify_insights_with_retries(
      max_passes=args.max_passes,
      client=client,
      eval_model=args.model_name,
      file_agent_env_id=args.file_agent_environment_id,
      fact_checking_env_id=args.fact_checking_agent_environment_id,
      df=df,
      file_agent_metadata_csv=args.file_agent_metadata_csv,
      output_csv=out_path,
      sandbox_timeout_sec=args.sandbox_timeout_sec,
      max_sandbox_concurrency=args.max_sandbox_concurrency,
  )

  df["verification_status"] = status_list
  df["verification_reason"] = reason_list

  counts = count_statuses(status_list)
  pass_count = counts[VerificationStatus.PASS.value]
  fail_count = counts[VerificationStatus.FAIL.value]
  skip_count = counts[VerificationStatus.SKIP.value]

  df.to_csv(out_path, index=False)
  logging.info(f"Updated insights with verification status written to {out_path}")

  logging.info("=" * 60)
  logging.info("Phase 3 Citation Verification Summary:")
  logging.info(f"  Total Insights: {len(df)}")
  logging.info(f"  ✅ PASS: {pass_count} ({pass_count/len(df)*100:.1f}%)")
  logging.info(f"  ❌ FAIL: {fail_count} ({fail_count/len(df)*100:.1f}%)")
  logging.info(f"  ⚠️ SKIP: {skip_count} ({skip_count/len(df)*100:.1f}%)")
  logging.info("=" * 60)

  sys.exit(0)


if __name__ == "__main__":
  asyncio.run(main())
